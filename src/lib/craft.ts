// 网文文风铁律：与本地红线扫描（inspect.ts）的词表对齐，
// 让 AI 写作/润色/改稿时主动避开会被扫描器扣分的表达。
export function buildStyleIronRules(): string {
  return `
【文风铁律——落笔前先读，逐条执行】
一、禁用/慎用词表（全章出现总数不超过3次，最好0次；意思要用具体动作和细节代替）：
  虚词：仿佛、似乎、宛如、犹如、好像
  时间副词：忽然、骤然、猛地、瞬间、刹那间、陡然、这一刻、那一瞬间
  连词：然而
  空泛抒情：心中五味杂陈、内心深处、眼神深邃、天地都安静了
  总结概括：这意味着、换句话说、值得注意的是
  表情套话：眼神一凝、嘴角勾起、眼中闪过一丝、眸光一闪
  情绪直给：心里一暖、激动万分、感动不已、心头一紧
  替代示例：把"他仿佛很震惊"改成"他手里的茶盏顿住了，茶水泼出来也没察觉"。

二、情绪不直接说：禁止写"他感到愤怒/害怕/开心"，用动作、语气、生理反应呈现（攥拳、冷笑、声音发紧、指节发白）。

三、抽象换具体：少用"强大、恐怖、厉害、无与伦比"，多用具体画面（剑光、裂痕、倒下的身影、碎裂的杯盏）。

四、对话一人一声：每个角色的用词、句式、口头禅、称呼必须不同；对话要有来有回和潜台词，禁止轮流独白，禁止对话后补一段解释。

五、短句优先：单句尽量不超过25字；少用"不仅…而且…""虽然…但是…"；一段不超过4行。

六、感官与细节：每个场景至少2种感官（视觉+声音/触觉/气味）；时间、距离、价格、招式名、地名尽量具体，不用"很多/非常/特别"。`;
}
